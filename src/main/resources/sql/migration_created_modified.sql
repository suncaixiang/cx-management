ALTER TABLE sys_role_permission ADD COLUMN created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE sys_role_permission ADD COLUMN modified DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP;

