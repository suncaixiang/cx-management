ALTER TABLE sys_role CHANGE COLUMN create_time created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE sys_role CHANGE COLUMN update_time modified DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP;

ALTER TABLE sys_permission CHANGE COLUMN create_time created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE sys_permission CHANGE COLUMN update_time modified DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP;

-- 关联表补充时间字段
ALTER TABLE sys_user_role ADD COLUMN created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP;
